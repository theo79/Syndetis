const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const output=execFileSync(process.argv[2]||'tmp/checks/json-tests.exe',{encoding:'utf8'}).trim().split(/\r?\n/);
assert.equal(output.length,2);
const full=JSON.parse(output[0]), mixed=JSON.parse(output[1]);
assert.ok(Buffer.byteLength(output[0])<16384);
assert.equal(full.firmware,'0.3.0');
assert.equal(full.switch_info.neighbors.length,4);
assert.equal(full.switch_info.neighbors[0].name,'"'.repeat(255));
assert.equal(full.switch_info.neighbors[0].chassis,'\\'.repeat(511));
assert.equal(full.switch_info.neighbors[0].port_id,'"'.repeat(511));
assert.equal(mixed.switch_info.neighbors[0].name,null);
assert.equal(mixed.switch_info.neighbors[1].name,'');
assert.equal(mixed.switch_info.neighbors[2].port_description,'<script>"quoted"\\line\n</script>');
console.log('PASS: actual HTTP JSON serializer: four worst-case escaped records fit; null/empty, quotes, backslashes and controls round-trip');
