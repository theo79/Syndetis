const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const output=execFileSync(process.argv[2]||'tmp/checks/json-tests.exe',{encoding:'utf8'}).trim().split(/\r?\n/);
assert.equal(output.length,3);
const full=JSON.parse(output[0]), mixed=JSON.parse(output[1]);
const manual=JSON.parse(output[2]);
assert.equal(manual.ethernet.ip,'192.168.10.250');
assert.equal(manual.addressing.mode,'MANUAL IP');
assert.equal(manual.addressing.prefix,24);
assert.equal(manual.addressing.gateway,null);
assert.equal(manual.dhcp.active,false);
assert.equal(manual.dhcp.blocked_by_manual,true);
assert.equal(manual.dhcp.ip,null);
assert.deepEqual(manual.dhcp.dns,[null,null]);
assert.ok(Buffer.byteLength(output[0])<16384);
assert.equal(full.firmware,'0.5.0');
assert.equal(full.dhcp.error_code,-1);
assert.equal(full.dhcp.error_step,'primary API');
assert.equal(full.dhcp.cleanup_code,0x5001);
assert.equal(full.dhcp.cleanup_step,'cleanup "API"');
assert.equal(full.switch_info.neighbors.length,4);
assert.equal(full.switch_info.neighbors[0].name,'"'.repeat(255));
assert.equal(full.switch_info.neighbors[0].chassis,'\\'.repeat(511));
assert.equal(full.switch_info.neighbors[0].port_id,'"'.repeat(511));
assert.equal(mixed.switch_info.neighbors[0].name,null);
assert.equal(mixed.switch_info.neighbors[1].name,'');
assert.equal(mixed.switch_info.neighbors[2].port_description,'<script>"quoted"\\line\n</script>');
